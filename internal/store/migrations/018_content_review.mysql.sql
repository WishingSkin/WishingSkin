CREATE TABLE IF NOT EXISTS texture_metadata (
 record_id CHAR(32) NOT NULL PRIMARY KEY,
 category VARCHAR(64) NOT NULL,
 tags TEXT NOT NULL,
 review_state VARCHAR(16) NOT NULL,
 review_reason VARCHAR(600) NOT NULL,
 FOREIGN KEY(record_id) REFERENCES texture_records(record_id) ON UPDATE CASCADE ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin;
