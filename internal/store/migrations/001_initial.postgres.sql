CREATE TABLE IF NOT EXISTS users (
    id BIGINT NOT NULL PRIMARY KEY,
    email VARCHAR(254) COLLATE "C" NOT NULL,
    email_key VARCHAR(254) COLLATE "C" NOT NULL UNIQUE,
    nickname VARCHAR(255) COLLATE "C" NOT NULL,
    password_hash TEXT COLLATE "C" NOT NULL,
    password_method VARCHAR(32) COLLATE "C" NOT NULL,
    password_salt TEXT COLLATE "C" NOT NULL,
    score BIGINT NOT NULL DEFAULT 0,
    permission INTEGER NOT NULL DEFAULT 0,
    banned BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS characters (
    id BIGINT NOT NULL PRIMARY KEY,
    user_id BIGINT NOT NULL,
    uuid VARCHAR(32) COLLATE "C" NOT NULL UNIQUE,
    name VARCHAR(16) COLLATE "C" NOT NULL,
    name_key VARCHAR(16) COLLATE "C" NOT NULL UNIQUE,
    skin_hash VARCHAR(128) COLLATE "C" NOT NULL DEFAULT '',
    cape_hash VARCHAR(128) COLLATE "C" NOT NULL DEFAULT '',
    model VARCHAR(8) COLLATE "C" NOT NULL DEFAULT 'default',
    FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS textures (
    hash VARCHAR(128) COLLATE "C" NOT NULL PRIMARY KEY,
    name VARCHAR(255) COLLATE "C" NOT NULL,
    kind VARCHAR(8) COLLATE "C" NOT NULL,
    model VARCHAR(8) COLLATE "C" NOT NULL,
    is_public BOOLEAN NOT NULL DEFAULT TRUE,
    deleted BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS settings (
    setting_key VARCHAR(64) COLLATE "C" NOT NULL PRIMARY KEY,
    value TEXT COLLATE "C" NOT NULL
);

CREATE TABLE IF NOT EXISTS web_sessions (
    token_hash CHAR(64) COLLATE "C" NOT NULL PRIMARY KEY,
    user_id BIGINT NOT NULL,
    expires_at BIGINT NOT NULL,
    FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS game_tokens (
    token_hash CHAR(64) COLLATE "C" NOT NULL PRIMARY KEY,
    client_token VARCHAR(128) COLLATE "C" NOT NULL,
    user_id BIGINT NOT NULL,
    profile_uuid VARCHAR(32) COLLATE "C" NOT NULL DEFAULT '',
    expires_at BIGINT NOT NULL,
    FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS migration_state (
    id INTEGER NOT NULL PRIMARY KEY,
    source_fingerprint CHAR(64) COLLATE "C" NOT NULL,
    status VARCHAR(16) COLLATE "C" NOT NULL,
    report TEXT COLLATE "C" NOT NULL
);
